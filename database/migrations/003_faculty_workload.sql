-- Faculty workload (SemesterReport) schema, on top of 002_lecturer_profile.sql
-- Target: Aurora PostgreSQL compatible SQL (PostgreSQL 15+)
--
-- Brings a 002 database up to the merged design in
-- database/data_schema/FacultyPortfolioWorkload/FacultyPortfolioWorkload.dbml (.sql is its export):
--   * new master table `department`, and `lecturer` gets `cognito_sub` + `department_id`
--   * the workload tables (member_position, rubric_*, evaluation_round, submission*, entry_*)
-- The Academic Portfolio tables of 002 are unchanged.
--
-- Differences from the dbdiagram export (it cannot draw these, see the end of the .dbml):
--   * submission_entry.submission_id, entry_assessment.entry_id and entry_evidence.entry_id
--     are ON DELETE CASCADE (the design marks them only in a note)
--   * CHECK constraints, partial/GIN indexes, the draft-only trigger and v_section_total
--   * indexes are created without CONCURRENTLY, because that cannot run inside a transaction
--
-- 002 + this file are the source of truth; backend/app/v2/models mirrors them.

BEGIN;

