-- ---------------------------------------------------------------------
-- Entries can only change while their submission is a draft
-- ---------------------------------------------------------------------

CREATE FUNCTION "submission_entry_draft_only"() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  target_submission uuid := CASE WHEN TG_OP = 'DELETE' THEN OLD.submission_id ELSE NEW.submission_id END;
  current_status submission_status;
BEGIN
  SELECT status INTO current_status FROM submission WHERE id = target_submission;
  -- NOT FOUND: the parent submission is being deleted (ON DELETE CASCADE), so let it through.
  IF FOUND AND current_status <> 'draft' THEN
    RAISE EXCEPTION 'submission % is %, entries can only change while it is a draft',
      target_submission, current_status
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

CREATE TRIGGER "trg_submission_entry_draft_only"
  BEFORE INSERT OR UPDATE OR DELETE ON "submission_entry"
  FOR EACH ROW EXECUTE FUNCTION "submission_entry_draft_only"();

-- ---------------------------------------------------------------------
-- Score per rubric section, capped at the section's cap
-- ---------------------------------------------------------------------

CREATE VIEW "v_section_total" AS
SELECT
  e.submission_id,
  s.id AS section_id,
  SUM(e.score) AS raw_score,
  LEAST(SUM(e.score), COALESCE(s.cap, SUM(e.score))) AS capped_score
FROM submission_entry e
JOIN rubric_item i ON i.id = e.item_id
JOIN rubric_section s ON s.id = i.section_id
GROUP BY e.submission_id, s.id, s.cap;

COMMIT;
